"""Reproduce the RANGE cross-asset gate.

The ETF book is deliberately narrow: a 1-minute volatility channel with a
small target and a wide stop.  The same geometry is tested here on the futures
contracts that look superficially similar (MES, MNQ, M2K, ZT, ...).  The test
is not a parameter search; it uses the published long-only baseline:

* 1 contract (the report's baseline size), regular hours
* 20% channel-edge entry, 0.20% minimum channel width
* 100-tick stop beyond the channel, 20%-of-channel target
* 120 one-minute-bar time stop and 15:55 ET flat
* one tick of entry/exit slippage plus the instrument's commission profile

Run from the repository root:

    python -m scripts.research_futures --data-root data/futures

Large parquet files stay outside Git.  The script writes:
    reports/futures_gate.csv
    reports/futures_gate.md
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd

from config.settings import instrument
from src.backtest import BacktestResult, run_backtest
from src.indicators import load_bars


@dataclass(frozen=True)
class Case:
    symbol: str
    data: str
    start: str
    end: str
    label: str


CASES: tuple[Case, ...] = (
    Case("MES", "mes_1m.parquet", "2019-05-06", "2026-10-23", "Micro E-mini S&P 500"),
    Case("MNQ", "mnq_1m.parquet", "2019-05-06", "2026-10-23", "Micro E-mini Nasdaq-100"),
    Case("M2K", "rty_1m_indicators.parquet", "2019-05-06", "2026-10-23", "Micro Russell 2000 (RTY proxy)"),
    Case("ZT", "zt_1m.parquet", "2019-05-06", "2026-10-23", "2-Year T-Note"),
    Case("ES", "es_1m.parquet", "2019-05-06", "2026-10-23", "E-mini S&P 500"),
    Case("NQ", "nq_1m.parquet", "2019-05-06", "2026-10-23", "E-mini Nasdaq-100"),
    Case("ZN", "zn_1m.parquet", "2019-05-06", "2026-10-23", "10-Year T-Note"),
    Case("CL", "cl_1m.parquet", "2019-05-06", "2026-10-23", "WTI Crude"),
    Case("GC", "gc_1m.parquet", "2019-05-06", "2026-10-23", "Gold"),
)


def _resolve(data_root: Path, name: str) -> Path:
    candidates = [
        data_root / name,
        Path("data") / name,
        Path("data") / "futures" / name,
    ]
    for candidate in candidates:
        if candidate.exists():
            return candidate
    raise FileNotFoundError(
        f"missing {name}; pass --data-root pointing at the directory that holds the parquet files"
    )


def _run(case: Case, data_root: Path) -> dict:
    path = _resolve(data_root, case.data)
    profile = instrument(case.symbol)
    frame = load_bars(
        path,
        timeframe="1m",
        start=case.start,
        end=case.end,
    )
    result: BacktestResult = run_backtest(
        frame,
        profile,
        start=case.start,
        end=case.end,
        sides="long",
        quantity=1,
        entry_zone=0.20,
        min_channel_pct=0.0020,
        stop_ticks=100.0,
        tp_mode="channel",
        tp_channel_pct=0.20,
        cooldown_bars=0,
        overlap=True,
        breakout_ticks=10.0,
        atr_filter=False,
        session="rth",
        max_hold_bars=120,
        flat_at_minute=15 * 60 + 55,
        timeframe="1m",
        assume_stop_first=True,
    )
    s = result.summary()
    net = float(s["net"])
    pf = float(s["pf"]) if pd.notna(s["pf"]) else 0.0
    positive_years = int(s["positive_years"])
    years = int(s["years"])
    if net <= 0:
        verdict = "negative after costs"
    elif pf < 1.20 or positive_years < max(1, years - 2):
        verdict = "positive but below deployment gate"
    else:
        verdict = "review"
    return {
        "symbol": case.symbol,
        "asset_class": profile.asset_class,
        "description": case.label,
        "data_file": case.data,
        "bars": int(result.bars),
        "trades": int(len(result.trades)),
        "win_rate": float(s["win_rate"]),
        "profit_factor": pf,
        "net": net,
        "net_per_month": float(s["net_per_month"]),
        "max_drawdown": float(s["max_drawdown"]),
        "positive_years": positive_years,
        "years": years,
        "avg_win": float(s["avg_win"]),
        "avg_loss": float(s["avg_loss"]),
        "verdict": verdict,
    }


def _markdown(rows: list[dict], generated: str) -> str:
    lines = [
        "# RANGE cross-asset gate",
        "",
        f"Generated by `python -m scripts.research_futures` on {generated}.",
        "",
        "Baseline: long-only, 1 contract, 20% channel entry, 0.20% minimum width,",
        "100-tick stop, 20%-of-channel target, 120-bar time stop, 15:55 ET flat,",
        "regular hours, one tick slippage and the profile's commission.",
        "",
        "This is a deliberately narrow test. It does not search for a futures",
        "parameter set and it is not evidence that no futures variant could work.",
        "It is evidence that the published ETF geometry does not transfer as-is.",
        "",
        "| Symbol | Asset | Trades | PF | Net | Net/month | Max DD | +Years | Verdict |",
        "|---|---|---:|---:|---:|---:|---:|---:|---|",
    ]
    for row in rows:
        lines.append(
            f"| **{row['symbol']}** | {row['asset_class']} | {row['trades']:,} | "
            f"{row['profit_factor']:.3f} | {row['net']:+,.2f} | "
            f"{row['net_per_month']:+,.2f} | {row['max_drawdown']:,.2f} | "
            f"{row['positive_years']}/{row['years']} | {row['verdict']} |"
        )
    lines += [
        "",
        "A blank or missing file is a data-availability problem, not a pass.",
        "The live runner accepts SPY and QQQ only; it refuses every futures symbol",
        "before opening a broker connection.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Run the RANGE ETF/futures cross-asset gate")
    parser.add_argument(
        "--data-root",
        default="data/futures",
        help="directory containing mes_1m.parquet, zt_1m.parquet, etc.",
    )
    parser.add_argument("--out", default="reports")
    parser.add_argument("--symbols", default="MES,MNQ,M2K,ZT,ES,NQ,ZN,CL,GC")
    args = parser.parse_args()

    wanted = {part.strip().upper() for part in args.symbols.split(",") if part.strip()}
    cases = [case for case in CASES if case.symbol in wanted]
    rows: list[dict] = []
    for case in cases:
        print(f"running {case.symbol} ...", flush=True)
        try:
            rows.append(_run(case, Path(args.data_root)))
        except Exception as exc:
            print(f"{case.symbol}: FAILED: {exc}", file=sys.stderr, flush=True)
            rows.append(
                {
                    "symbol": case.symbol,
                    "asset_class": instrument(case.symbol).asset_class,
                    "description": case.label,
                    "data_file": case.data,
                    "bars": 0,
                    "trades": 0,
                    "win_rate": 0.0,
                    "profit_factor": 0.0,
                    "net": 0.0,
                    "net_per_month": 0.0,
                    "max_drawdown": 0.0,
                    "positive_years": 0,
                    "years": 0,
                    "avg_win": 0.0,
                    "avg_loss": 0.0,
                    "verdict": f"not run: {exc}",
                }
            )

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    frame = pd.DataFrame(rows)
    frame.to_csv(out / "futures_gate.csv", index=False)
    generated = datetime.now(tz=timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    (out / "futures_gate.md").write_text(_markdown(rows, generated), encoding="utf-8")
    print(frame[["symbol", "trades", "profit_factor", "net", "verdict"]].to_string(index=False))
    return 0 if all(not str(row["verdict"]).startswith("not run") for row in rows) else 1


if __name__ == "__main__":
    raise SystemExit(main())
