-- SkyQ RANGE reporting schema (PostgreSQL 14+)
-- The application can also create this schema via `python -m scripts.init_db`.
-- Run with: psql "$DATABASE_URL" -f sql/001_schema.sql

BEGIN;

CREATE TABLE IF NOT EXISTS instruments (
    symbol              VARCHAR(16) PRIMARY KEY,
    name                VARCHAR(120) NOT NULL,
    asset_class         VARCHAR(16) NOT NULL,
    exchange            VARCHAR(32) NOT NULL,
    tick_size           DOUBLE PRECISION NOT NULL,
    multiplier          DOUBLE PRECISION NOT NULL,
    live_enabled        BOOLEAN NOT NULL DEFAULT FALSE,
    note                TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS backtest_runs (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    strategy            VARCHAR(32) NOT NULL DEFAULT 'SkyQ RANGE',
    symbol              VARCHAR(16) NOT NULL REFERENCES instruments(symbol),
    "window"            VARCHAR(32) NOT NULL,
    "start"             TIMESTAMPTZ,
    "end"               TIMESTAMPTZ,
    quantity            INTEGER NOT NULL DEFAULT 1000,
    starting_equity     DOUBLE PRECISION NOT NULL DEFAULT 1000000,
    preset              VARCHAR(240) NOT NULL DEFAULT '',
    source_report       VARCHAR(240) NOT NULL DEFAULT '',
    generated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_run_strategy_symbol_window UNIQUE (strategy, symbol, "window")
);

CREATE TABLE IF NOT EXISTS backtest_metrics (
    run_id              INTEGER PRIMARY KEY REFERENCES backtest_runs(id) ON DELETE CASCADE,
    trades              INTEGER NOT NULL DEFAULT 0,
    win_rate            DOUBLE PRECISION NOT NULL DEFAULT 0,
    profit_factor       DOUBLE PRECISION NOT NULL DEFAULT 0,
    net                 DOUBLE PRECISION NOT NULL DEFAULT 0,
    return_pct          DOUBLE PRECISION NOT NULL DEFAULT 0,
    max_drawdown        DOUBLE PRECISION NOT NULL DEFAULT 0,
    max_drawdown_pct    DOUBLE PRECISION NOT NULL DEFAULT 0,
    sharpe              DOUBLE PRECISION NOT NULL DEFAULT 0,
    net_per_month       DOUBLE PRECISION NOT NULL DEFAULT 0,
    positive_months     INTEGER NOT NULL DEFAULT 0,
    months              INTEGER NOT NULL DEFAULT 0,
    positive_years      INTEGER NOT NULL DEFAULT 0,
    years               INTEGER NOT NULL DEFAULT 0,
    costs               DOUBLE PRECISION NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS trades (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id              INTEGER NOT NULL REFERENCES backtest_runs(id) ON DELETE CASCADE,
    symbol              VARCHAR(16) NOT NULL,
    side                VARCHAR(8) NOT NULL,
    bar_time            TIMESTAMPTZ,
    signal_time         TIMESTAMPTZ,
    entry_time          TIMESTAMPTZ,
    entry_price         DOUBLE PRECISION NOT NULL DEFAULT 0,
    stop_price          DOUBLE PRECISION NOT NULL DEFAULT 0,
    target_price        DOUBLE PRECISION NOT NULL DEFAULT 0,
    exit_time           TIMESTAMPTZ,
    exit_price          DOUBLE PRECISION NOT NULL DEFAULT 0,
    exit_reason         VARCHAR(32) NOT NULL DEFAULT '',
    quantity            INTEGER NOT NULL DEFAULT 0,
    gross_pnl           DOUBLE PRECISION NOT NULL DEFAULT 0,
    costs               DOUBLE PRECISION NOT NULL DEFAULT 0,
    net_pnl             DOUBLE PRECISION NOT NULL DEFAULT 0,
    bars_held           INTEGER NOT NULL DEFAULT 0,
    channel_width       DOUBLE PRECISION NOT NULL DEFAULT 0,
    zone_price          DOUBLE PRECISION NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS ix_trades_run_exit ON trades(run_id, exit_time);
CREATE INDEX IF NOT EXISTS ix_trades_symbol_exit ON trades(symbol, exit_time);

CREATE TABLE IF NOT EXISTS equity_points (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id              INTEGER NOT NULL REFERENCES backtest_runs(id) ON DELETE CASCADE,
    date                TIMESTAMPTZ NOT NULL,
    daily_pnl           DOUBLE PRECISION NOT NULL DEFAULT 0,
    equity              DOUBLE PRECISION NOT NULL DEFAULT 1000000,
    drawdown            DOUBLE PRECISION NOT NULL DEFAULT 0,
    CONSTRAINT uq_equity_run_date UNIQUE (run_id, date)
);
CREATE INDEX IF NOT EXISTS ix_equity_run_date ON equity_points(run_id, date);

CREATE TABLE IF NOT EXISTS futures_gate (
    symbol              VARCHAR(16) PRIMARY KEY,
    asset_class         VARCHAR(16) NOT NULL DEFAULT 'FUT',
    description         VARCHAR(160) NOT NULL DEFAULT '',
    data_file           VARCHAR(240) NOT NULL DEFAULT '',
    bars                INTEGER NOT NULL DEFAULT 0,
    trades              INTEGER NOT NULL DEFAULT 0,
    win_rate            DOUBLE PRECISION NOT NULL DEFAULT 0,
    profit_factor       DOUBLE PRECISION NOT NULL DEFAULT 0,
    net                 DOUBLE PRECISION NOT NULL DEFAULT 0,
    net_per_month       DOUBLE PRECISION NOT NULL DEFAULT 0,
    max_drawdown        DOUBLE PRECISION NOT NULL DEFAULT 0,
    positive_years      INTEGER NOT NULL DEFAULT 0,
    years               INTEGER NOT NULL DEFAULT 0,
    verdict             VARCHAR(160) NOT NULL DEFAULT '',
    generated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS audit_events (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    actor               VARCHAR(80) NOT NULL DEFAULT 'local',
    action              VARCHAR(80) NOT NULL,
    detail              JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX IF NOT EXISTS ix_audit_created ON audit_events(created_at);

COMMIT;
